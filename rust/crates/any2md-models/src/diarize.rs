//! Shared diarization post-processing.
//!
//! Both Sortformer and Nemotron-3 end in the same frame→segment conversion
//! (`Sortformer._preds_to_segments`): per-speaker thresholding, run-length
//! extraction, minimum-duration filter, optional gap merge, then a global sort
//! by start time. Kept MLX-free so it can be unit-tested against vectors
//! produced by the Python implementation.

/// One diarized span.
#[derive(Debug, Clone, PartialEq)]
pub struct Segment {
    pub start: f32,
    pub end: f32,
    pub speaker: usize,
}

/// Convert frame-level speaker probabilities into segments.
///
/// `preds` is row-major `[frames][speakers]`.
pub fn preds_to_segments(
    preds: &[Vec<f32>],
    frame_duration: f32,
    threshold: f32,
    min_duration: f32,
    merge_gap: f32,
) -> Vec<Segment> {
    let n_spk = preds.first().map(|r| r.len()).unwrap_or(0);
    let mut segments: Vec<Segment> = Vec::new();

    for spk in 0..n_spk {
        // activity[i] = preds[i][spk] > threshold, with False sentinels on both ends
        let activity: Vec<bool> = preds.iter().map(|row| row[spk] > threshold).collect();
        if !activity.iter().any(|a| *a) {
            continue;
        }
        let mut padded = vec![false];
        padded.extend_from_slice(&activity);
        padded.push(false);

        let mut starts = Vec::new();
        let mut ends = Vec::new();
        for i in 0..padded.len() - 1 {
            let delta = padded[i + 1] as i32 - padded[i] as i32;
            if delta == 1 {
                starts.push(i);
            } else if delta == -1 {
                ends.push(i);
            }
        }

        let mut spk_segments: Vec<Segment> = Vec::new();
        for (s, e) in starts.iter().zip(ends.iter()) {
            let start = *s as f32 * frame_duration;
            let end = *e as f32 * frame_duration;
            if end - start >= min_duration {
                spk_segments.push(Segment { start, end, speaker: spk });
            }
        }

        if merge_gap > 0.0 && spk_segments.len() > 1 {
            let mut merged: Vec<Segment> = vec![spk_segments[0].clone()];
            for seg in &spk_segments[1..] {
                let last = merged.last_mut().expect("non-empty");
                if seg.start - last.end <= merge_gap {
                    last.end = seg.end;
                } else {
                    merged.push(seg.clone());
                }
            }
            spk_segments = merged;
        }

        segments.extend(spk_segments);
    }

    segments.sort_by(|a, b| a.start.partial_cmp(&b.start).unwrap_or(std::cmp::Ordering::Equal));
    segments
}

/// Merge same-speaker segments separated by <= `merge_gap` across the whole
/// timeline (any2md's `_merge_diarization_segments`, used after chunked
/// streaming).
pub fn merge_same_speaker(mut segments: Vec<Segment>, merge_gap: f32) -> Vec<Segment> {
    if segments.is_empty() {
        return segments;
    }
    segments.sort_by(|a, b| a.start.partial_cmp(&b.start).unwrap_or(std::cmp::Ordering::Equal));
    let mut merged: Vec<Segment> = vec![segments[0].clone()];
    for seg in &segments[1..] {
        let last = merged.last_mut().expect("non-empty");
        if seg.speaker == last.speaker && seg.start - last.end <= merge_gap {
            last.end = last.end.max(seg.end);
        } else {
            merged.push(seg.clone());
        }
    }
    merged
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Vectors generated by running mlx_audio's `Sortformer._preds_to_segments`
    /// on the same synthetic probabilities (see rust/parity/diarize_segments.py).
    fn fixture_preds() -> Vec<Vec<f32>> {
        // 12 frames, 2 speakers
        vec![
            vec![0.9, 0.1],
            vec![0.8, 0.2],
            vec![0.2, 0.7],
            vec![0.1, 0.9],
            vec![0.1, 0.85],
            vec![0.6, 0.4],
            vec![0.4, 0.6],
            vec![0.3, 0.3],
            vec![0.95, 0.05],
            vec![0.9, 0.1],
            vec![0.2, 0.2],
            vec![0.7, 0.3],
        ]
    }

    #[test]
    fn segments_match_python() {
        let segs = preds_to_segments(&fixture_preds(), 0.08, 0.5, 0.0, 0.0);
        let got: Vec<(u32, u32, usize)> = segs
            .iter()
            .map(|s| {
                (
                    (s.start * 1000.0).round() as u32,
                    (s.end * 1000.0).round() as u32,
                    s.speaker,
                )
            })
            .collect();
        assert_eq!(
            got,
            vec![
                (0, 160, 0),
                (160, 400, 1),
                (400, 480, 0),
                (480, 560, 1),
                (640, 800, 0),
                (880, 960, 0),
            ]
        );
        // global sort by start time
        let starts: Vec<u32> = got.iter().map(|g| g.0).collect();
        let mut sorted = starts.clone();
        sorted.sort_unstable();
        assert_eq!(starts, sorted);
    }

    #[test]
    fn min_duration_filters_short_runs() {
        let segs = preds_to_segments(&fixture_preds(), 0.08, 0.5, 0.1, 0.0);
        let got: Vec<(u32, u32, usize)> = segs
            .iter()
            .map(|s| {
                (
                    (s.start * 1000.0).round() as u32,
                    (s.end * 1000.0).round() as u32,
                    s.speaker,
                )
            })
            .collect();
        // python: [(0,160,0), (160,400,1), (640,800,0)]
        assert_eq!(got, vec![(0, 160, 0), (160, 400, 1), (640, 800, 0)]);
    }

    #[test]
    fn merge_gap_joins_same_speaker_runs() {
        let segs = preds_to_segments(&fixture_preds(), 0.08, 0.5, 0.0, 0.3);
        let got: Vec<(u32, u32, usize)> = segs
            .iter()
            .map(|s| {
                (
                    (s.start * 1000.0).round() as u32,
                    (s.end * 1000.0).round() as u32,
                    s.speaker,
                )
            })
            .collect();
        // python: [(0,960,0), (160,560,1)]
        assert_eq!(got, vec![(0, 960, 0), (160, 560, 1)]);
    }

    #[test]
    fn stream_merge_joins_across_chunks() {
        let segs = vec![
            Segment { start: 0.0, end: 5.0, speaker: 0 },
            Segment { start: 5.1, end: 9.0, speaker: 0 },
            Segment { start: 9.0, end: 12.0, speaker: 1 },
        ];
        let merged = merge_same_speaker(segs, 0.3);
        assert_eq!(merged.len(), 2);
        assert_eq!(merged[0].end, 9.0);
    }
}
